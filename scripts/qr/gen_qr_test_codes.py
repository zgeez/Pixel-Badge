"""Generate the QR screening codes for the 32 x 32 display and verify them.

Encodes each test payload as a QR code of the given version and places it in
the centre of the 32 x 32 frame. Version 1 keeps the standard four-module
quiet zone; larger versions fit only with a reduced quiet zone and are
experiments, not the standard output. Each frame is rendered as the matrix
shows it (lit background, unlit dark modules, on a dark surround) in both
polarities and checked with an independent decoder (ZXing-C++). The frames are
written as C++ source for the firmware.

The committed codes use representative payloads, not the badge's real URL:
alphanumeric uppercase URLs at the Version 1 capacity of each EC level. Codes
for other payloads (for example personal links) go to a local file instead:

    gen_qr_test_codes.py --out-cpp build/qr-local/qr_test_codes.cpp \\
        --code NAME VERSION EC MIN_QUIET PAYLOAD [--code ...]

and the firmware uses that file when CONFIG_APP_QR_CODES_FILE names it.

Requires segno and zxing-cpp (and Pillow), e.g. in a virtual environment:
    python -m venv .venv && .venv/Scripts/pip install segno zxing-cpp pillow
    .venv/Scripts/python scripts/qr/gen_qr_test_codes.py
then run the formatter (scripts/dev.ps1 format or make format).
"""

import argparse
import sys
from pathlib import Path

import segno
import zxingcpp
from PIL import Image

SIZE = 32
QUIET = 4
REPO = Path(__file__).resolve().parents[2]
OUT_HPP = REPO / "firmware" / "include" / "badge" / "qr_test_codes.hpp"
OUT_CPP = REPO / "firmware" / "src" / "services" / "qr_test_codes.cpp"

# (name, payload, version, EC level, minimum quiet zone). Version 1
# alphanumeric capacity: L 25, M 20, Q 16.
CODES = [
    ("V1-L", "HTTPS://EXAMPLE.COM", 1, "L", QUIET),
    ("V1-M", "HTTPS://EXAMPLE.COM", 1, "M", QUIET),
    ("V1-Q", "HTTPS://IANA.ORG", 1, "Q", QUIET),
]

HEADER = """/*
 * SPDX-License-Identifier: MIT
 *
 * QR screening codes for the 32 x 32 display. Generated by
 * scripts/qr/gen_qr_test_codes.py; do not edit.
 */

#pragma once

#include <stddef.h>
#include <stdint.h>

#include "badge/test_pattern.hpp"

namespace badge
{

struct QrTestCode {
	const char *name;
	const char *payload;
	/* Frame in normal polarity: lit = light module or quiet zone. */
	uint8_t frame[kFrameBytes];
};

extern const QrTestCode kQrTestCodes[];
extern const size_t kQrTestCodeCount;

} // namespace badge
"""


def frame_for(payload, ec, version=1, min_quiet=QUIET):
    qr = segno.make_qr(payload, error=ec, version=version, boost_error=False)
    if qr.version != version or qr.error != ec:
        sys.exit(f"{payload!r}: got version {qr.version} EC {qr.error}, need V{version}-{ec}")
    matrix = [list(row) for row in qr.matrix]  # 1 = dark module
    n = len(matrix)
    offset = (SIZE - n) // 2
    if offset < min_quiet or SIZE - offset - n < min_quiet:
        sys.exit(f"{payload!r}: quiet zone below {min_quiet} modules")
    # lit[y][x] = True where the matrix shows light (background, light modules).
    lit = [[True] * SIZE for _ in range(SIZE)]
    for y in range(n):
        for x in range(n):
            if matrix[y][x]:
                lit[offset + y][offset + x] = False
    return lit, offset, n


def render(lit, inverted, scale=12, surround=8):
    """Matrix as the camera sees it: lit LEDs white, unlit black, dark surround."""
    side = (SIZE + 2 * surround) * scale
    img = Image.new("L", (side, side), 0)
    px = img.load()
    for y in range(SIZE):
        for x in range(SIZE):
            if lit[y][x] != inverted:
                for dy in range(scale):
                    for dx in range(scale):
                        px[(x + surround) * scale + dx, (y + surround) * scale + dy] = 255
    return img


def decode(img, payload):
    results = zxingcpp.read_barcodes(img, formats=zxingcpp.BarcodeFormat.QRCode,
                                     try_invert=True)
    texts = [r.text for r in results]
    return payload in texts, texts


def to_bytes(lit):
    out = []
    for y in range(SIZE):
        for byte in range(SIZE // 8):
            v = 0
            for bit in range(8):
                if lit[y][byte * 8 + bit]:
                    v |= 0x80 >> bit
            out.append(v)
    return out


def write_cpp(path, entries):
    lines = ["/*", " * SPDX-License-Identifier: MIT", " *",
             " * Generated by scripts/qr/gen_qr_test_codes.py; do not edit. Each code was",
             " * checked with ZXing-C++ in both polarities when generated (see its log).",
             " */", "", "#include \"badge/qr_test_codes.hpp\"", "", "namespace badge", "{", "",
             "const QrTestCode kQrTestCodes[] = {"]
    for name, payload, data in entries:
        lines.append(f"\t{{\"{name}\", \"{payload}\", {{")
        for i in range(0, len(data), 8):
            lines.append("\t\t" + ", ".join(f"0x{b:02X}" for b in data[i:i + 8]) + ",")
        lines.append("\t}},")
    lines += ["};", "",
              "const size_t kQrTestCodeCount = sizeof(kQrTestCodes) / sizeof(kQrTestCodes[0]);",
              "", "} // namespace badge", ""]
    path.write_text("\n".join(lines), encoding="utf-8", newline="\n")


def main():
    ap = argparse.ArgumentParser(description="Generate QR screening codes for the matrix.")
    ap.add_argument("--code", nargs=5, action="append",
                    metavar=("NAME", "VERSION", "EC", "MIN_QUIET", "PAYLOAD"))
    ap.add_argument("--out-cpp", type=Path, help="write only this source file (local codes)")
    args = ap.parse_args()
    codes = CODES
    if args.code:
        if not args.out_cpp:
            sys.exit("--code needs --out-cpp: custom codes are not written to the repository")
        codes = [(n, p, int(v), ec, int(q)) for n, v, ec, q, p in args.code]

    entries = []
    for name, payload, version, ec, min_quiet in codes:
        lit, offset, n = frame_for(payload, ec, version, min_quiet)
        quiet = (offset, SIZE - offset - n)
        reduced = min(quiet) < QUIET
        for inverted in (False, True):
            ok, texts = decode(render(lit, inverted), payload)
            pol = "inverted" if inverted else "normal"
            print(f"{name} {pol:8s} {payload!r}: {'OK' if ok else 'FAIL'} (decoded {texts})")
            if not ok and not reduced:
                sys.exit(1)
        print(f"{name}: {n}x{n} modules at offset {offset}, quiet zone {quiet[0]}/{quiet[1]}"
              f" modules{' (reduced: experiment only)' if reduced else ''}")
        entries.append((name, payload, to_bytes(lit)))

    if args.out_cpp:
        args.out_cpp.parent.mkdir(parents=True, exist_ok=True)
        write_cpp(args.out_cpp, entries)
        print(f"wrote {args.out_cpp}")
        return
    OUT_HPP.write_text(HEADER, encoding="utf-8", newline="\n")
    write_cpp(OUT_CPP, entries)
    print(f"wrote {OUT_HPP.relative_to(REPO)} and {OUT_CPP.relative_to(REPO)}")


if __name__ == "__main__":
    main()
